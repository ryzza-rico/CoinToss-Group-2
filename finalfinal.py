def calculate_probabilities(name, data_string):
    heads = data_string.count('1')
    tails = data_string.count('0')
    total = len(data_string)

    p_heads = (heads / total) * 100
    p_tails = (tails / total) * 100

    return {
        "Name": name,
        "Heads": heads,
        "Tails": tails,
        "Total": total,
        "P_Heads": p_heads,
        "P_Tails": p_tails,
        "Bias": abs(p_heads - 50)
    }

def running_probability(data_string):
    heads = 0
    probs = []

    for i, flip in enumerate(data_string, start=1):
        if flip == '1':
            heads += 1

        probs.append((heads / i) * 100)

    return probs

