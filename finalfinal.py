def compute_probability(data):
    results = {}
    total_heads = 0
    total_tails = 0

    for coin_class, (heads, tails) in data.items():
        h = len(heads)
        t = len(tails)
        total = h + t

        results[coin_class] = {
            "heads": h,
            "tails": t,
            "p_heads": h / total,
            "p_tails": t / total
        }

        total_heads += h
        total_tails += t

    overall_total = total_heads + total_tails

    overall = {
        "heads": total_heads,
        "tails": total_tails,
        "p_heads": total_heads / overall_total,
        "p_tails": total_tails / overall_total
    }

    return results, overall


